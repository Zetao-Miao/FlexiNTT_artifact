def _emit_testbench(spec: TransposeOperatorSpec, rows: int, burst_starts: list[int],
                    expected: int, end_cycle: int, legacy: bool) -> str:
    n, w = spec.rows, spec.elementWidth
    bits = n * w
    L = []
    L.append('`timescale 1ns / 1ps')
    L.append('')
    L.append(f'// Self-checking testbench for {spec.name}.')
    L.append(f'// Streams {rows} rows ({rows // n} matrices) {len(burst_starts)} times, at cycles '
             + ', '.join(str(b) for b in burst_starts) + '.')
    if legacy:
        L.append('// Checks every output row at the cycle testvectors/y_cycle.txt gives')
        L.append("// (the design's twin, transpose_model.py, run over this stimulus).")
    else:
        L.append('// Rows are taken as data_out_valid delivers them: each burst\'s first row must')
        max_wait = 0 if spec.architecture == 'bmb' else n - 1
        L.append(f'// land within LATENCY + 0..{max_wait} cycles of the burst start, the rows of a burst')
        L.append('// must be contiguous, and no valid may appear outside them. testvectors/y_cycle.txt')
        L.append("// holds the twin's own prediction (transpose_model.py over this stimulus) and is")
        L.append('// printed beside the measured cycle, not asserted on.')
    L.append('// PASS/FAIL strings match scripts/run_remote_sim.py grep patterns (SUCCESS!, PASS All, FAILED:).')
    L.append(f'module {spec.name}_tb ();')
    L.append('    `define CLK_P         10')
    L.append('    `define CLK_HP        5')
    L.append(f'    localparam int N         = {n};')
    L.append(f'    localparam int W         = {w};')
    L.append(f'    localparam int ROWS      = {rows};')
    L.append(f'    localparam int RUNS      = {len(burst_starts)};')
    L.append(f'    localparam int EXPECTED  = {expected};')
    L.append(f'    localparam int END_CYCLE = {end_cycle};')
    L.append('')
    L.append('    logic clk;')
    L.append('    initial clk = 1\'b0;')
    L.append('    always #`CLK_HP clk = ~clk;')
    L.append('')
    L.append('    logic data_valid;')
    for i in range(n):
        L.append(f'    logic [{w - 1}:0] x_in_{i};')
    if not legacy:
        L.append('    logic data_out_valid;')
    for i in range(n):
        L.append(f'    logic [{w - 1}:0] y_out_{i};')
    L.append('')
    L.append(f'    logic [{bits - 1}:0] x_in_ts  [0:ROWS-1];')
    L.append(f'    logic [{bits - 1}:0] y_out_ts [0:ROWS-1];')
    L.append('    logic [31:0]  y_cycle  [0:EXPECTED-1];')
    L.append('')
    L.append('    initial begin')
    L.append('        $readmemh("../../../../../testvectors/x_in.txt",    x_in_ts );')
    L.append('        $readmemh("../../../../../testvectors/y_out.txt",   y_out_ts);')
    L.append('        $readmemh("../../../../../testvectors/y_cycle.txt", y_cycle );')
    L.append('    end')
    L.append('')
    L.append(f'    {spec.name} DUT (')
    L.append('        .clk(clk),')
    L.append('        .data_valid(data_valid),')
    for i in range(n):
        L.append(f'        .x_in_{i}(x_in_{i}),')
    if not legacy:
        L.append('        .data_out_valid(data_out_valid),')
    for i in range(n):
        suffix = ',' if i < n - 1 else ''
        L.append(f'        .y_out_{i}(y_out_{i}){suffix}')
    L.append('    );')
    L.append('')
    # lane 0 in the LSBs, as the packed testvectors are written
    concat_in = ', '.join(f'x_in_{i}' for i in range(n - 1, -1, -1))
    concat_out = ', '.join(f'y_out_{i}' for i in range(n - 1, -1, -1))
    L.append(f'    logic [{bits - 1}:0] x_row;')
    L.append(f'    assign {{{concat_in}}} = x_row;')
    L.append(f'    logic [{bits - 1}:0] y_out_packed;')
    L.append(f'    assign y_out_packed = {{{concat_out}}};')
    L.append('')
    L.append('    // cyc = the number of rising edges so far: cycle c is the interval after edge c')
    L.append('    int cyc;')
    L.append('    initial cyc = 0;')
    L.append('    always @(posedge clk) cyc <= cyc + 1;')
    L.append('')
    L.append('    // Driver: the row for cycle c is presented #1 after edge c and sampled by edge c+1.')
    L.append('    initial begin')
    L.append('        data_valid = 1\'b0;')
    L.append('        x_row      = \'0;')
    L.append('    end')
    L.append('    always @(posedge clk) begin')
    L.append('        #1;')
    conds = []
    for b in burst_starts:
        conds.append((b, f'(cyc >= {b} && cyc < {b} + ROWS)', f'cyc - {b}'))
    first = True
    for b, cond, idx in conds:
        L.append(f'        {"if" if first else "end else if"} {cond} begin')
        L.append(f'            x_row      = x_in_ts[{idx}];')
        L.append('            data_valid = 1\'b1;')
        first = False
    L.append('        end else begin')
    L.append('            data_valid = 1\'b0;')
    L.append('        end')
    L.append('    end')
    L.append('')
    L.append('    // Checker: outputs visible during cycle c are read #2 after edge c.')
    if legacy:
        L.append('    int out_k;')
        L.append('    int correct_cnt;')
        L.append('    int wrong_cnt;')
        L.append('    initial begin')
        L.append('        out_k        = 0;')
        L.append('        correct_cnt  = 0;')
        L.append('        wrong_cnt    = 0;')
        L.append('    end')
        L.append('    always @(posedge clk) begin')
        L.append('        #2;')
        L.append('        if (out_k < EXPECTED && cyc == y_cycle[out_k]) begin')
        L.append('            // `===` alone is NOT X-safe: X === X is true, so a run whose')
        L.append('            // $readmemh silently failed would score a full PASS having checked')
        L.append('            // nothing. Guard on $isunknown so any X anywhere is a failure.')
        L.append('            if (!$isunknown(y_out_packed) && !$isunknown(y_out_ts[out_k % ROWS])')
        L.append('                && y_out_packed === y_out_ts[out_k % ROWS]) begin')
        L.append('                correct_cnt = correct_cnt + 1;')
        L.append('            end else begin')
        L.append('                wrong_cnt = wrong_cnt + 1;')
        L.append('                $display("=================================================================================");')
        L.append('                $display("Output row %0d WRONG at cycle %0d", out_k, cyc);')
        L.append('                if ($isunknown(y_out_ts[out_k % ROWS]))')
        L.append('                    $display("  golden is X -- testvectors not loaded (check the $readmemh path)");')
        L.append('                if ($isunknown(y_out_packed))')
        L.append('                    $display("  DUT output is X -- undriven logic or X-valued inputs");')
        for i in range(n):
            hi, lo = (i + 1) * w - 1, i * w
            L.append(f'                if (y_out_{i} !== y_out_ts[out_k % ROWS][{hi}:{lo}]) begin')
            L.append(f'                    $display("  y_out_{i} module    output: %h", y_out_{i});')
            L.append(f'                    $display("  y_out_{i} reference output: %h", y_out_ts[out_k % ROWS][{hi}:{lo}]);')
            L.append('                end')
        L.append('                $display("=================================================================================");')
        L.append('            end')
        L.append('            out_k = out_k + 1;')
        L.append('        end')
        L.append('        if (cyc == END_CYCLE) begin')
        L.append('            if (wrong_cnt == 0 && correct_cnt == EXPECTED) begin')
        L.append('                $display("SUCCESS!");')
        L.append('                $display("PASS All %0d Testvectors!", EXPECTED);')
        L.append('            end else begin')
        L.append('                $display("TO BE DEBUGGED...");')
        L.append('                $display("FAILED: %0d out of %0d testvectors failed (%0d wrong or missing rows)",')
        L.append('                         EXPECTED - correct_cnt, EXPECTED, EXPECTED - correct_cnt);')
        L.append('            end')
        L.append('            $finish();')
        L.append('        end')
        L.append('    end')
    else:
        # Rows are taken as data_out_valid delivers them. The module's frame
        # (mbm) has whatever phase it had at power-up -- in the RTL simulation
        # cycle 0, on a netlist or in silicon anything -- so a burst's first row
        # is checked against the window the design allows, LATENCY plus 0..MAX_WAIT
        # after the burst's start, not against one predicted cycle; the twin's
        # prediction (y_cycle.txt, phase 0) is printed beside the measured wait.
        L.append(f'    localparam int LATENCY  = {spec.latency};')
        L.append(f'    localparam int MAX_WAIT = {0 if spec.architecture == "bmb" else n - 1};')
        L.append('    int burst_start [0:RUNS-1];')
        L.append('    initial begin')
        for b, start in enumerate(burst_starts):
            L.append(f'        burst_start[{b}] = {start};')
        L.append('    end')
        L.append('    int out_k;')
        L.append('    int correct_cnt;')
        L.append('    int wrong_cnt;')
        L.append('    int spurious_cnt;')
        L.append('    int timing_err;')
        L.append('    int broken_cnt;')
        L.append('    int waited;')
        L.append('    initial begin')
        L.append('        out_k        = 0;')
        L.append('        correct_cnt  = 0;')
        L.append('        wrong_cnt    = 0;')
        L.append('        spurious_cnt = 0;')
        L.append('        timing_err   = 0;')
        L.append('        broken_cnt   = 0;')
        L.append('    end')
        L.append('    always @(posedge clk) begin')
        L.append('        #2;')
        L.append('        if (data_out_valid === 1\'b1) begin')
        L.append('            if (out_k < EXPECTED) begin')
        L.append('                if (out_k % ROWS == 0) begin')
        L.append('                    waited = cyc - burst_start[out_k / ROWS] - LATENCY;')
        L.append('                    if (waited < 0 || waited > MAX_WAIT) begin')
        L.append('                        timing_err = timing_err + 1;')
        L.append('                        $display("burst %0d: first row at cycle %0d, %0d cycle(s) after start + LATENCY %0d; the design allows 0..%0d",')
        L.append('                                 out_k / ROWS, cyc, waited, LATENCY, MAX_WAIT);')
        L.append('                    end else begin')
        L.append('                        $display("burst %0d: first row at cycle %0d, wait %0d (twin predicted %0d at frame phase 0)",')
        L.append('                                 out_k / ROWS, cyc, waited, y_cycle[out_k] - burst_start[out_k / ROWS] - LATENCY);')
        L.append('                    end')
        L.append('                end')
        L.append('                // `===` alone is NOT X-safe: X === X is true, so a run whose')
        L.append('                // $readmemh silently failed would score a full PASS having checked')
        L.append('                // nothing. Guard on $isunknown so any X anywhere is a failure.')
        L.append('                if (!$isunknown(y_out_packed) && !$isunknown(y_out_ts[out_k % ROWS])')
        L.append('                    && y_out_packed === y_out_ts[out_k % ROWS]) begin')
        L.append('                    correct_cnt = correct_cnt + 1;')
        L.append('                end else begin')
        L.append('                    wrong_cnt = wrong_cnt + 1;')
        L.append('                    $display("=================================================================================");')
        L.append('                    $display("Output row %0d WRONG at cycle %0d", out_k, cyc);')
        L.append('                    if ($isunknown(y_out_ts[out_k % ROWS]))')
        L.append('                        $display("  golden is X -- testvectors not loaded (check the $readmemh path)");')
        L.append('                    if ($isunknown(y_out_packed))')
        L.append('                        $display("  DUT output is X -- undriven logic or X-valued inputs");')
        for i in range(n):
            hi, lo = (i + 1) * w - 1, i * w
            L.append(f'                    if (y_out_{i} !== y_out_ts[out_k % ROWS][{hi}:{lo}]) begin')
            L.append(f'                        $display("  y_out_{i} module    output: %h", y_out_{i});')
            L.append(f'                        $display("  y_out_{i} reference output: %h", y_out_ts[out_k % ROWS][{hi}:{lo}]);')
            L.append('                    end')
        L.append('                    $display("=================================================================================");')
        L.append('                end')
        L.append('                out_k = out_k + 1;')
        L.append('            end else begin')
        L.append('                spurious_cnt = spurious_cnt + 1;')
        L.append('                $display("data_out_valid is 1 at cycle %0d after every expected row", cyc);')
        L.append('            end')
        L.append('        end else if (data_out_valid !== 1\'b0) begin')
        L.append('            spurious_cnt = spurious_cnt + 1;')
        L.append('            $display("data_out_valid is %b at cycle %0d", data_out_valid, cyc);')
        L.append('        end else if (out_k % ROWS != 0 && out_k < EXPECTED) begin')
        L.append('            broken_cnt = broken_cnt + 1;')
        L.append('            $display("data_out_valid low at cycle %0d inside a burst, after row %0d", cyc, out_k - 1);')
        L.append('        end')
        L.append('        if (cyc == END_CYCLE) begin')
        L.append('            if (wrong_cnt == 0 && spurious_cnt == 0 && timing_err == 0 && broken_cnt == 0 && correct_cnt == EXPECTED) begin')
        L.append('                $display("SUCCESS!");')
        L.append('                $display("PASS All %0d Testvectors!", EXPECTED);')
        L.append('            end else begin')
        L.append('                $display("TO BE DEBUGGED...");')
        L.append('                $display("FAILED: %0d out of %0d testvectors failed (%0d wrong rows, %0d missing, %0d unexpected data_out_valid cycles, %0d bursts off their window, %0d valid gaps inside a burst)",')
        L.append('                         EXPECTED - correct_cnt + spurious_cnt + timing_err + broken_cnt, EXPECTED, wrong_cnt, EXPECTED - out_k, spurious_cnt, timing_err, broken_cnt);')
        L.append('            end')
        L.append('            $finish();')
        L.append('        end')
        L.append('    end')
    L.append('')
    L.append('endmodule')
    return '\n'.join(L) + '\n'


