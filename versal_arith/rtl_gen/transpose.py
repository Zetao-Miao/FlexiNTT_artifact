def _emit_top(spec: TransposeOperatorSpec, legacy: bool) -> str:
    n, w = spec.rows, spec.elementWidth
    module = f'{spec.architecture}_matrix_transpose'
    L = []
    L.append('`timescale 1ns / 1ps')
    L.append('')
    L.append(f'// {spec.name}: {n} x {n} streaming matrix transpose, {w}-bit elements,')
    L.append(f'// architecture {spec.architecture} ({module}). Generated by rtl_gen.transpose.')
    L.append(f'// One row per cycle in on x_in_<i> while data_valid is high; the transposed')
    L.append(f'// rows out on y_out_<i>, {spec.latency} cycle(s) later'
             + ('.' if spec.architecture == 'bmb' else ' for a burst on the frame.'))
    if not legacy:
        L.append(f'// Barrel shifter register placement: REG_FLAGS = {list(spec.regFlags)} '
                 f'({sum(spec.regFlags)} register(s) per shifter).')
    L.append(f'module {spec.name} (')
    L.append('    input  logic clk,')
    L.append('    input  logic data_valid,')
    for i in range(n):
        L.append(f'    input  logic [{w - 1}:0] x_in_{i},')
    if not legacy:
        L.append('    output logic data_out_valid,')
    for i in range(n):
        suffix = ',' if i < n - 1 else ''
        L.append(f'    output logic [{w - 1}:0] y_out_{i}{suffix}')
    L.append(');')
    L.append('')
    L.append(f'    logic [{w - 1}:0] rows_in  [0:{n - 1}];')
    L.append(f'    logic [{w - 1}:0] rows_out [0:{n - 1}];')
    L.append('')
    for i in range(n):
        L.append(f'    assign rows_in[{i}] = x_in_{i};')
    for i in range(n):
        L.append(f'    assign y_out_{i} = rows_out[{i}];')
    L.append('')
    L.append(f'    {module} #(')
    L.append(f'        .STREAM_SIZE   ({n}),')
    if legacy:
        L.append(f'        .ELEMENT_WIDTH ({w})')
    else:
        L.append(f'        .ELEMENT_WIDTH ({w}),')
        L.append(f"        .REG_FLAGS     (32'h{flags_to_reg_flags(spec.regFlags):08X})")
    L.append('    ) u_transpose (')
    L.append('        .clk            (clk),')
    L.append('        .data_valid     (data_valid),')
    L.append('        .data_in        (rows_in),')
    if not legacy:
        L.append('        .data_out_valid (data_out_valid),')
    L.append('        .data_out       (rows_out)')
    L.append('    );')
    L.append('')
    L.append('endmodule')
    return '\n'.join(L) + '\n'


