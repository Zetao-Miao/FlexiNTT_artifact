def static_module_files(architecture: str, legacy: bool = False) -> tuple[str, ...]:
    """The hand-written modules a design of this architecture needs (the
    original modules, `legacy`, had no delay_line)."""
    common = _STATIC_COMMON[1:] if legacy else _STATIC_COMMON
    return common + (f'{architecture}_matrix_transpose.sv',)


def _copy_static(names, dest_dir: Path, static_dir: Path) -> list[Path]:
    dest_dir.mkdir(parents=True, exist_ok=True)
    out = []
    for name in names:
        src = static_dir / name
        if not src.is_file():
            raise FileNotFoundError(
                f"missing {src}: the matrix transpose's hand-written modules live in "
                f"versal_arith/rtl/matrix_transpose/"
            )
        dest = dest_dir / name
        dest.write_text(src.read_text(encoding='utf-8'), encoding='utf-8')
        out.append(dest)
    return out


