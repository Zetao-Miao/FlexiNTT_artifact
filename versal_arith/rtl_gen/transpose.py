def Transpose_RTL_gen(spec: TransposeOperatorSpec,
                      pipeline_stages: int | None = None,
                      gen_testbench: bool = True,
                      visualization: bool = False,  # accepted for the Operator.emitRtl template; ignored (a transpose has no bit-heap to draw)
                      x_in: list[list[int]] | None = None,
                      y_out: list[list[int]] | None = None,
                      gap_cycles: int = 1,
                      preamble_cycles: int = 20,
                      test_size: int = 4,
                      seed: int | None = None,
                      static_dir: str | os.PathLike | None = None,
                      legacy_latency: int | None = None) -> dict:
    """Write the design into the cwd (`RTL_generated/`, `testvectors/`).

    x_in       rows of the matrices to stream, one list of `rows` ints per
               cycle, `T * rows` of them; sampled when None
    y_out      the transposed rows, in the same shape; the plain transpose of
               each matrix when None
    gap_cycles data_valid-low cycles between the two bursts (default 1)
    visualization is accepted for the `Operator.emitRtl` template's uniform
               call and ignored.
    pipeline_stages  must equal the registers per shifter the spec's flags
               place, when given -- the placement is the spec's

    static_dir / legacy_latency: point at another copy of the hand-written
    modules and drive their original port list (no REG_FLAGS, no
    data_out_valid) with output rows expected a fixed `legacy_latency` after
    their input rows -- the campaign's way of running the original modules
    through the same testbench. Not for normal use.

    Returns the run's metadata. `rows` is the matrix dimension when
    `gen_testbench=False` and the number of streamed input rows once a
    testbench is generated -- a sim twin must reproduce that, since the gate
    checks it.
    """
    n, w = spec.rows, spec.elementWidth
    flags = check_flags(n, spec.regFlags)
    legacy = legacy_latency is not None
    if pipeline_stages is not None and pipeline_stages != sum(flags):
        raise ValueError(
            f'{spec.name}: pipeline_stages={pipeline_stages} but the spec places '
            f'{sum(flags)} register(s) per shifter; the placement is the scheme\'s'
        )
    if gap_cycles < 0:
        raise ValueError(f'{spec.name}: gap_cycles must be >= 0, got {gap_cycles}')

    rtl_dir = Path('RTL_generated')
    tv_dir = Path('testvectors')
    rtl_dir.mkdir(parents=True, exist_ok=True)
    files = _copy_static(static_module_files(spec.architecture, legacy), rtl_dir,
                         Path(static_dir) if static_dir is not None else _STATIC_DIR)

    top = rtl_dir / f'{spec.name}.sv'
    top.write_text(_emit_top(spec, legacy), encoding='utf-8')
    files.append(top)

    meta = {
        'name': spec.name,
        'architecture': spec.architecture,
        'rows': n,
        'element_width': w,
        'reg_flags': list(flags),
        'latency': spec.latency,
        'files': [str(p) for p in files],
    }
    if not gen_testbench:
        return meta

    rng = random.Random(seed)
    if x_in is None:
        x_in = sample_rows(spec, test_size, rng)
    rows = len(x_in)
    if rows == 0 or rows % n:
        raise ValueError(f'{spec.name}: x_in holds {rows} rows, not a positive multiple of {n}')
    for k, row in enumerate(x_in):
        if len(row) != n:
            raise ValueError(f'{spec.name}: x_in row {k} has {len(row)} elements, expected {n}')
    if y_out is None:
        y_out = []
        for m in range(rows // n):
            y_out += transpose_rows(x_in[m * n:(m + 1) * n])
    if len(y_out) != rows:
        raise ValueError(f'{spec.name}: y_out holds {len(y_out)} rows for {rows} input rows')

    # The stimulus the testbench drives, then the twin over it.
    burst_starts = [preamble_cycles, preamble_cycles + rows + gap_cycles]
    schedule: list = [None] * preamble_cycles + list(x_in) + [None] * gap_cycles + list(x_in)
    if legacy:
        cycles = [b + k + legacy_latency for b in burst_starts for k in range(rows)]
    else:
        model = (BmbTranspose if spec.architecture == 'bmb' else MbmTranspose)(n, flags)
        trace = run_schedule(model, schedule, extra_cycles=3 * n + sum(flags) + 8)
        got = valid_rows(trace)
        want = list(y_out) + list(y_out)
        if [r for _, r in got] != want:
            raise RuntimeError(
                f'{spec.name}: the twin does not transpose this stimulus as expected '
                f'({len(got)} valid rows for {len(want)} goldens) -- transpose_model '
                f'and the generator disagree'
            )
        cycles = [c for c, _ in got]
    end_cycle = cycles[-1] + 2 * n + 8      # room for a burst waiting on the frame

    tv_dir.mkdir(parents=True, exist_ok=True)
    _write_rows(tv_dir / 'x_in.txt', x_in, w)
    _write_rows(tv_dir / 'y_out.txt', y_out, w)
    with open(tv_dir / 'y_cycle.txt', 'w', encoding='utf-8') as f:
        for c in cycles:
            f.write(f'{c:08X}\n')

    tb = rtl_dir / f'{spec.name}_tb.sv'
    tb.write_text(_emit_testbench(spec, rows, burst_starts, len(cycles), end_cycle, legacy),
                  encoding='utf-8')
    files.append(tb)
    meta.update({
        'files': [str(p) for p in files],
        'rows': rows,   # NOTE: overwrites the matrix dimension set above with the number of streamed rows; runMatrixTranspose.py reads this meaning
        'burst_starts': burst_starts,
        'gap_cycles': gap_cycles,
        'output_cycles': cycles,
        'end_cycle': end_cycle,
    })
    return meta


