def _pack_row(row, w: int) -> str:
    """Lane 0 in the least significant bits, two's complement at `w` bits."""
    packed = 0
    for lane, v in enumerate(row):
        packed |= (int(to_twos_complement_hex(v, w), 16)) << (w * lane)
    digits = -(-(len(row) * w) // 4)
    return f'{packed:0{digits}X}'


def _write_rows(path: Path, rows, w: int) -> None:
    with open(path, 'w', encoding='utf-8') as f:
        for row in rows:
            f.write(_pack_row(row, w) + '\n')


def sample_rows(spec: TransposeOperatorSpec, matrices: int, rng: random.Random) -> list[list[int]]:
    """`matrices` matrices of uniform samples over the whole element register."""
    n, w = spec.rows, spec.elementWidth
    lo, hi = (-(1 << (w - 1)), (1 << (w - 1)) - 1) if spec.isSigned else (0, (1 << w) - 1)
    return [[rng.randint(lo, hi) for _ in range(n)] for _ in range(matrices * n)]


