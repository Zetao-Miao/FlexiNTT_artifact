def _emit_barrel_top(name: str, n: int, w: int, flags, legacy: bool) -> str:
    from transpose_model import barrel_depth
    d = barrel_depth(n)
    L = []
    L.append('`timescale 1ns / 1ps')
    L.append('')
    L.append(f'// {name}: barrel_shift over {n} elements of {w} bits, on its own. Generated by rtl_gen.transpose.')
    if not legacy:
        L.append(f'// REG_FLAGS = {list(flags)} ({sum(flags)} register(s)).')
    L.append(f'module {name} (')
    L.append('    input  logic clk,')
    L.append(f'    input  logic [{d - 1}:0] shift,')
    for i in range(n):
        L.append(f'    input  logic [{w - 1}:0] x_in_{i},')
    for i in range(n):
        suffix = ',' if i < n - 1 else ''
        L.append(f'    output logic [{w - 1}:0] y_out_{i}{suffix}')
    L.append(');')
    L.append('')
    L.append(f'    logic [{w - 1}:0] rows_in  [0:{n - 1}];')
    L.append(f'    logic [{w - 1}:0] rows_out [0:{n - 1}];')
    for i in range(n):
        L.append(f'    assign rows_in[{i}] = x_in_{i};')
    for i in range(n):
        L.append(f'    assign y_out_{i} = rows_out[{i}];')
    L.append('')
    L.append('    barrel_shift #(')
    L.append(f'        .STREAM_SIZE   ({n}),')
    if legacy:
        L.append(f'        .ELEMENT_WIDTH ({w})')
    else:
        L.append(f'        .ELEMENT_WIDTH ({w}),')
        L.append(f"        .REG_FLAGS     (32'h{flags_to_reg_flags(flags):08X})")
    L.append('    ) u_barrel_shift (')
    L.append('        .clk      (clk),')
    L.append('        .data_in  (rows_in),')
    L.append('        .shift    (shift),')
    L.append('        .data_out (rows_out)')
    L.append('    );')
    L.append('')
    L.append('endmodule')
    return '\n'.join(L) + '\n'


def _emit_barrel_testbench(name: str, n: int, w: int, cycles: int, preamble: int,
                           expected: int, end_cycle: int) -> str:
    from transpose_model import barrel_depth
    d = barrel_depth(n)
    bits = n * w
    L = []
    L.append('`timescale 1ns / 1ps')
    L.append('')
    L.append(f'// Self-checking testbench for {name}: a row and a shift every cycle for {cycles} cycles,')
    L.append('// every output row checked at the cycle testvectors/y_cycle.txt gives.')
    L.append('// PASS/FAIL strings match scripts/run_remote_sim.py grep patterns (SUCCESS!, PASS All, FAILED:).')
    L.append(f'module {name}_tb ();')
    L.append('    `define CLK_P         10')
    L.append('    `define CLK_HP        5')
    L.append(f'    localparam int CYCLES    = {cycles};')
    L.append(f'    localparam int PRE       = {preamble};')
    L.append(f'    localparam int EXPECTED  = {expected};')
    L.append(f'    localparam int END_CYCLE = {end_cycle};')
    L.append('')
    L.append('    logic clk;')
    L.append('    initial clk = 1\'b0;')
    L.append('    always #`CLK_HP clk = ~clk;')
    L.append('')
    L.append(f'    logic [{d - 1}:0] shift;')
    for i in range(n):
        L.append(f'    logic [{w - 1}:0] x_in_{i};')
    for i in range(n):
        L.append(f'    logic [{w - 1}:0] y_out_{i};')
    L.append('')
    L.append(f'    logic [{bits - 1}:0] x_in_ts  [0:CYCLES-1];')
    L.append(f'    logic [{d - 1}:0]    shift_ts [0:CYCLES-1];')
    L.append(f'    logic [{bits - 1}:0] y_out_ts [0:EXPECTED-1];')
    L.append('    logic [31:0]  y_cycle  [0:EXPECTED-1];')
    L.append('    initial begin')
    L.append('        $readmemh("../../../../../testvectors/x_in.txt",    x_in_ts );')
    L.append('        $readmemh("../../../../../testvectors/shift.txt",   shift_ts);')
    L.append('        $readmemh("../../../../../testvectors/y_out.txt",   y_out_ts);')
    L.append('        $readmemh("../../../../../testvectors/y_cycle.txt", y_cycle );')
    L.append('    end')
    L.append('')
    L.append(f'    {name} DUT (')
    L.append('        .clk(clk),')
    L.append('        .shift(shift),')
    for i in range(n):
        L.append(f'        .x_in_{i}(x_in_{i}),')
    for i in range(n):
        suffix = ',' if i < n - 1 else ''
        L.append(f'        .y_out_{i}(y_out_{i}){suffix}')
    L.append('    );')
    L.append('')
    concat_in = ', '.join(f'x_in_{i}' for i in range(n - 1, -1, -1))
    concat_out = ', '.join(f'y_out_{i}' for i in range(n - 1, -1, -1))
    L.append(f'    logic [{bits - 1}:0] x_row;')
    L.append(f'    assign {{{concat_in}}} = x_row;')
    L.append(f'    logic [{bits - 1}:0] y_out_packed;')
    L.append(f'    assign y_out_packed = {{{concat_out}}};')
    L.append('')
    L.append('    int cyc;')
    L.append('    initial cyc = 0;')
    L.append('    always @(posedge clk) cyc <= cyc + 1;')
    L.append('')
    L.append('    initial begin')
    L.append('        shift = \'0;')
    L.append('        x_row = \'0;')
    L.append('    end')
    L.append('    always @(posedge clk) begin')
    L.append('        #1;')
    L.append('        if (cyc >= PRE && cyc < PRE + CYCLES) begin')
    L.append('            x_row = x_in_ts[cyc - PRE];')
    L.append('            shift = shift_ts[cyc - PRE];')
    L.append('        end else begin')
    L.append('            x_row = \'0;')
    L.append('            shift = \'0;')
    L.append('        end')
    L.append('    end')
    L.append('')
    L.append('    int out_k;')
    L.append('    int correct_cnt;')
    L.append('    int wrong_cnt;')
    L.append('    initial begin')
    L.append('        out_k       = 0;')
    L.append('        correct_cnt = 0;')
    L.append('        wrong_cnt   = 0;')
    L.append('    end')
    L.append('    always @(posedge clk) begin')
    L.append('        #2;')
    L.append('        if (out_k < EXPECTED && cyc == y_cycle[out_k]) begin')
    L.append('            if (!$isunknown(y_out_packed) && !$isunknown(y_out_ts[out_k]) && y_out_packed === y_out_ts[out_k]) begin')
    L.append('                correct_cnt = correct_cnt + 1;')
    L.append('            end else begin')
    L.append('                wrong_cnt = wrong_cnt + 1;')
    L.append('                $display("Output row %0d WRONG at cycle %0d", out_k, cyc);')
    L.append('                $display("  module    output: %h", y_out_packed);')
    L.append('                $display("  reference output: %h", y_out_ts[out_k]);')
    L.append('            end')
    L.append('            out_k = out_k + 1;')
    L.append('        end')
    L.append('        if (cyc == END_CYCLE) begin')
    L.append('            if (wrong_cnt == 0 && correct_cnt == EXPECTED) begin')
    L.append('                $display("SUCCESS!");')
    L.append('                $display("PASS All %0d Testvectors!", EXPECTED);')
    L.append('            end else begin')
    L.append('                $display("TO BE DEBUGGED...");')
    L.append('                $display("FAILED: %0d out of %0d testvectors failed", EXPECTED - correct_cnt, EXPECTED);')
    L.append('            end')
    L.append('            $finish();')
    L.append('        end')
    L.append('    end')
    L.append('')
    L.append('endmodule')
    return '\n'.join(L) + '\n'


def BarrelShift_RTL_gen(name: str, n: int, w: int, flags=None,
                        gen_testbench: bool = True, cycles: int = 200,
                        preamble_cycles: int = 20, seed: int | None = None,
                        static_dir: str | os.PathLike | None = None,
                        legacy_latency: int | None = None) -> dict:
    """The barrel shifter alone: a top with `shift` and per-index ports, and a
    testbench that drives a random row and a random shift every cycle and
    checks `y(c) = rotate(x(c - L), shift(c - L))` for L the latency. Written
    into the cwd like `Transpose_RTL_gen`; `static_dir` / `legacy_latency`
    drive the original module the same way."""
    from transpose_model import barrel_depth, barrel_latency, default_flags
    d = barrel_depth(n)
    legacy = legacy_latency is not None
    flags = check_flags(n, default_flags(n) if flags is None else flags)
    latency = legacy_latency if legacy else barrel_latency(flags)
    rtl_dir = Path('RTL_generated')
    tv_dir = Path('testvectors')
    files = _copy_static(('barrel_shift.sv',), rtl_dir,
                         Path(static_dir) if static_dir is not None else _STATIC_DIR)
    top = rtl_dir / f'{name}.sv'
    top.write_text(_emit_barrel_top(name, n, w, flags, legacy), encoding='utf-8')
    files.append(top)
    meta = {'name': name, 'rows': n, 'element_width': w, 'reg_flags': list(flags),
            'latency': latency, 'files': [str(p) for p in files]}
    if not gen_testbench:
        return meta
    rng = random.Random(seed)
    lo, hi = 0, (1 << w) - 1
    x = [[rng.randint(lo, hi) for _ in range(n)] for _ in range(cycles)]
    shifts = [rng.randrange(n) for _ in range(cycles)]
    # the output during cycle c is the row driven at c - L rotated by its shift;
    # cycles before the first row reaches the output are not checked
    expected_rows, cyc = [], []
    for k in range(cycles):
        c = preamble_cycles + k + latency
        row, s = x[k], shifts[k]
        expected_rows.append([row[(b - s) % n] for b in range(n)])
        cyc.append(c)
    end_cycle = cyc[-1] + 4
    tv_dir.mkdir(parents=True, exist_ok=True)
    _write_rows(tv_dir / 'x_in.txt', x, w)
    _write_rows(tv_dir / 'y_out.txt', expected_rows, w)
    with open(tv_dir / 'shift.txt', 'w', encoding='utf-8') as f:
        for s in shifts:
            f.write(f'{s:0{-(-d // 4)}X}\n')
    with open(tv_dir / 'y_cycle.txt', 'w', encoding='utf-8') as f:
        for c in cyc:
            f.write(f'{c:08X}\n')
    tb = rtl_dir / f'{name}_tb.sv'
    tb.write_text(_emit_barrel_testbench(name, n, w, cycles, preamble_cycles, len(cyc), end_cycle),
                  encoding='utf-8')
    files.append(tb)
    meta.update({'files': [str(p) for p in files], 'output_cycles': cyc, 'end_cycle': end_cycle})
    return meta
