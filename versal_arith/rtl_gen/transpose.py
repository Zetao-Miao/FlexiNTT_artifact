"""Transpose_RTL_gen -- a streaming matrix transpose as a synthesizable design.

The transposes themselves are the hand-written, parameterised modules in
`rtl/matrix_transpose/` (`barrel_shift`, `BRAM`, `delay_line`, and
`bmb_matrix_transpose` / `mbm_matrix_transpose`); this generator copies the
ones a design needs into the run directory, the way the DSP flow copies
`DSP58Block.sv` (`delay_line` there takes a DEPTH parameter; the
DSP-multiplier backend emits a different module of the same name taking
CYCLES -- see `rtl_gen/dsp_multiplier/inner_backends.py:_delay_line_module`
-- so the two trees must not be compiled into one library until one is
renamed), and writes around them:

    RTL_generated/<name>.sv       the top: clk, data_valid, x_in_<i>, data_out_valid,
                                  y_out_<i> (per-index named ports at the element
                                  width, as the NTT wrapper has), packing the lanes
                                  into the module's arrays and passing the barrel
                                  shifter's REG_FLAGS
    RTL_generated/<name>_tb.sv    a self-checking testbench
    testvectors/x_in.txt          one packed row per line, lane 0 in the LSBs
    testvectors/y_out.txt         the transposed rows, same packing
    testvectors/y_cycle.txt       the cycle at which each output row must appear

The testbench streams the rows twice -- a burst of T matrices back-to-back,
then the same burst again after `gap_cycles` of data_valid low (one cycle by
default, the case the original control logic could not take) -- and checks
the rows as `data_out_valid` delivers them: every burst's first row must land
within the window the design allows (its latency, plus up to N-1 cycles of
waiting for the frame in mbm), every burst delivers its rows contiguously,
and valid is low in between. The twin (`transpose_model`) is run here over the
same stimulus and its predicted cycles (testvectors/y_cycle.txt, for a frame
at phase 0 as in the RTL simulation) are printed beside the measured waits --
a netlist or silicon has whatever frame phase it had at power-up, which is
exactly why the check is a window and not one cycle. The goldens are the
plain transpose of each matrix (or the caller's, when the model hands them
over).

Cycle convention: cycle 0 is the interval before the first rising edge; the
row driven during cycle c (at #1 after edge c) is sampled by the edge ending
it, and the outputs the checker reads at #2 after edge c are those visible
during cycle c. The twin's tick c consumes and returns exactly those.
"""
